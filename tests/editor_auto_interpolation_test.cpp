#include "mikudancestudio/editor_session.hpp"
#include "mikudancestudio/bone_key_interpolation.hpp"
#include "bone_key_interpolation_fixture.hpp"
#include <fstream>
#include <iostream>
using namespace mikudancestudio;
using namespace editor;
using namespace format;
std::string reason;
#define CHECK(x)                                                                                   \
    do {                                                                                           \
        if (!(x)) {                                                                                \
            std::cerr << __LINE__ << ": " << #x << " " << reason << '\n';                          \
            return 1;                                                                              \
        }                                                                                          \
    } while (false)
using Curves = std::vector<std::array<std::uint8_t, 16>>;
Curves CurvesOf(const EditorSession& session) {
    std::vector<std::vector<PmmBoneKey>> chains;
    if (!PmmTrackChains(session.Document().models[0].boneKeys, chains))
        return {};
    Curves curves;
    for (const auto& key : chains.at(1))
        curves.push_back(key.interpolation);
    return curves;
}
bool Curve(const std::array<std::uint8_t, 16>& bytes, unsigned lane,
           std::array<std::uint8_t, 4> expected) {
    for (unsigned i = 0; i < 4; ++i)
        if (bytes[lane + i * 4] != expected[i])
            return false;
    return true;
}
int main(int argc, char** argv) {
    CHECK(argc == 2);
    std::uint64_t hash = 14695981039346656037ull;
    unsigned cases = 0;
    bone_curve_fixture::Visit([&](auto keys, auto index, auto lane) {
        keyframe_edit::RebuildBoneCurve([&](auto i) -> auto& { return keys[i]; }, 2, index, lane);
        bone_curve_fixture::Hash(hash, keys);
        ++cases;
    });
    // Frozen by the hash-verified x64 RVA C9070 oracle, never generated by
    // the portable implementation or refreshed during normal CI.
    CHECK(cases == 200 && hash == 0xef40b2f667094778ull);
    EditorSession session;
    CHECK(session.AutoInterpolation());
    const auto root = std::filesystem::absolute(argv[1]);
    CHECK(session.ImportModel(root / "pose.pmd", reason));
    const auto insert = [&](unsigned frame, float position) {
        return session.SetBone(0, 1, {position, 0, 0}, {0, 0, 0, 1}, reason) &&
               session.Register({{Track::Bone, 0, 1, frame}}, reason);
    };
    CHECK(insert(10, 1));
    CHECK(Curve(CurvesOf(session)[1], 0, {64, 0, 64, 127}));
    CHECK(Curve(CurvesOf(session)[1], 3, {20, 20, 107, 107}));
    CHECK(insert(20, 2));
    CHECK(Curve(CurvesOf(session)[1], 0, {64, 0, 87, 87}));
    CHECK(Curve(CurvesOf(session)[2], 0, {40, 40, 64, 127}));
    CHECK(insert(15, 3));
    const auto peak = CurvesOf(session);
    CHECK(peak.size() == 4);
    CHECK(Curve(peak[1], 0, {64, 0, 87, 87}));
    CHECK(Curve(peak[2], 0, {40, 40, 64, 127}));
    CHECK(Curve(peak[3], 0, {64, 0, 64, 127}));
    CHECK(insert(15, -1));
    const auto valley = CurvesOf(session);
    CHECK(Curve(valley[1], 0, {64, 0, 64, 127}));
    CHECK(Curve(valley[2], 0, {64, 0, 64, 127}));
    for (unsigned cycle = 0; cycle < 3; ++cycle) {
        CHECK(session.Undo(reason));
        CHECK(CurvesOf(session) == peak);
        CHECK(session.Redo(reason));
        CHECK(CurvesOf(session) == valley);
    }
    session.Selected().keys = {{Track::Bone, 0, 1, 15}};
    CHECK(session.MoveInterpolationPoint(0, 0, 31, 47, reason));
    const auto custom = CurvesOf(session);
    const auto revision = session.Revision();
    const auto* runtime = &session.Runtime();
    session.SetAutoInterpolation(false);
    CHECK(session.Revision() == revision && &session.Runtime() == runtime);
    CHECK(insert(15, -2));
    CHECK(CurvesOf(session) == custom);
    CHECK(insert(25, 4));
    const auto manual = CurvesOf(session);
    CHECK(manual.size() == 5);
    for (unsigned lane = 0; lane < 4; ++lane)
        CHECK(Curve(manual.back(), lane, {20, 20, 107, 107}));
    CHECK(std::equal(custom.begin(), custom.end(), manual.begin()));
    const auto beforeFailure = session.Revision();
    session.SetAutoInterpolation(true);
    CHECK(!session.Register({{Track::Bone, 0, 1, 15}, {Track::Bone, 0, 999, 15}}, reason));
    CHECK(CurvesOf(session) == manual && session.Revision() == beforeFailure);
    session.SetAutoInterpolation(false);
    const auto writer = [](const auto& path, const auto& bytes, auto&) {
        std::ofstream file(path, std::ios::binary);
        file.write(reinterpret_cast<const char*>(bytes.data()), std::streamsize(bytes.size()));
        return bool(file);
    };
    CHECK(session.Save(root / "auto-curves.pmm", writer, reason));
    CHECK(session.Open(root / "auto-curves.pmm", reason));
    CHECK(!session.AutoInterpolation() && CurvesOf(session) == manual);
    CHECK(session.New(reason) && !session.AutoInterpolation());
    // The typed adapter rejects invalid links and missing frames atomically.
    PmmKeyTrack<PmmBoneKey> track;
    track.dense.resize(1);
    track.dense[0].interpolation.fill(42);
    CHECK(!RebuildPmmBoneInterpolation(track, 0, 10));
    CHECK(track.dense[0].interpolation[0] == 42);
    track.dense[0].next = 99;
    CHECK(!RebuildPmmBoneInterpolation(track, 0, 0));
    CHECK(track.dense[0].interpolation[0] == 42);
    std::cout
        << "Automatic curves: 200 original kernel cases, neighboring keys, history, manual overwrite and persistence passed\n";
}
