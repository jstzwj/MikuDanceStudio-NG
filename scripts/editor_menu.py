"""Generate the portable menu tree from the original MMD resource source.

`--check` also compares both languages against the binary RT_MENU records;
it runs without rc.exe, Qt, a display server or the original executable.
"""
import argparse
import json
from pathlib import Path
import re
import struct
from dialog_rc import parse_res

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'include/mikudancestudio/mmd_editor_menu.hpp'
POPUPS = ['file', 'edit', 'view', 'background', 'morph', 'physics', 'capture', 'help', 'enhance']


def source_menus():
    commands = dict(re.findall(r'#define (MDS_CMD_\w+) (\d+)',
                              (ROOT / 'include/mikudancestudio/menu_commands.h').read_text()))
    source = (ROOT / 'res/templates/menu/menus.rc').read_text(encoding='utf-16')
    menus = {}
    for resource, code in [('SAMPLE02E', 'en'), ('SAMPLE02', 'ja')]:
        lines = iter(source.split(resource + ' MENU\n', 1)[1].splitlines())
        assert next(lines) == 'BEGIN'
        depth, pending, popup = 0, False, 0
        entries = []
        for line in lines:
            line = line.strip()
            if line == 'BEGIN':
                assert pending
                depth += 1
                pending = False
            elif line == 'END':
                depth -= 1
                if depth < 0:
                    break
            else:
                match = re.fullmatch(r'POPUP "([^"]*)"', line)
                if match:
                    entries.append(dict(kind='Popup', depth=depth, command=0,
                                        id='menu.' + POPUPS[popup], text=match[1]))
                    popup += 1
                    pending = True
                    continue
                match = re.fullmatch(r'MENUITEM "([^"]*)", (MDS_CMD_\w+|0)', line)
                assert match, f'Unsupported menu source: {line}'
                text, name = match.groups()
                command = int(commands[name]) if name != '0' else 0
                assert command or not text
                entries.append(dict(kind='Action' if command else 'Separator', depth=depth,
                                    command=command, id=f'command.{command}' if command else '',
                                    text=text))
        assert depth == -1 and popup == len(POPUPS) and not pending
        assert sorted(e['command'] for e in entries if e['command']) == list(range(200, 303))
        menus[code] = entries
    assert [{k: v for k, v in e.items() if k != 'text'} for e in menus['en']] == [
        {k: v for k, v in e.items() if k != 'text'} for e in menus['ja']]
    return menus


def reference_menus():
    """Independent binary decoder: ordering, nesting, IDs and UTF-16 labels."""
    resources = parse_res((ROOT / 'res/gen_resources.res').read_bytes())
    menus = {}
    for resource, code in [('SAMPLE02E', 'en'), ('SAMPLE02', 'ja')]:
        blob, = resources[(('ord', 4), ('str', resource))]
        assert struct.unpack_from('<HH', blob) == (0, 0)
        offset, entries = 4, []

        def branch(depth):
            nonlocal offset
            while True:
                flags, = struct.unpack_from('<H', blob, offset)
                offset += 2
                assert flags & ~(0x10 | 0x80) == 0
                command = 0
                if not flags & 0x10:
                    command, = struct.unpack_from('<H', blob, offset)
                    offset += 2
                end = offset
                while blob[end:end + 2] != b'\0\0':
                    end += 2
                label = blob[offset:end].decode('utf-16-le')
                offset = end + 2
                kind = 'Popup' if flags & 0x10 else 'Action' if command else 'Separator'
                entries.append(dict(kind=kind, depth=depth, command=command, text=label))
                if flags & 0x10:
                    branch(depth + 1)
                if flags & 0x80:
                    return

        branch(0)
        assert offset == len(blob)
        menus[code] = entries
    return menus


def generated_header(entries):
    rows = '\n'.join('    {MenuKind::%s, %d, %d, "%s"},' %
                     (e['kind'], e['depth'], e['command'], e['id']) for e in entries)
    return '''// Generated by scripts/editor_menu.py from res/templates/menu/menus.rc.
// Do not hand-edit: the --check gate compares the original binary menu records.
#pragma once
namespace mikudancestudio::ui {
enum class MenuKind { Popup, Action, Separator };
struct MenuEntry {
    MenuKind kind;
    unsigned depth;
    int command;
    const char* message;
};
inline constexpr MenuEntry kMmdMenu[] = {
''' + rows + '''
};
}
'''


def run(check):
    menus, references = source_menus(), reference_menus()
    for code, entries in menus.items():
        assert [{k: v for k, v in e.items() if k != 'id'} for e in entries] == references[code], code
    files = {HEADER: generated_header(menus['en'])}
    for code in ['en', 'ja', 'zh_CN']:
        path = ROOT / 'res/i18n' / (code + '.json')
        catalog = json.loads(path.read_text(encoding='utf-8'))
        if code != 'zh_CN':
            catalog.update({e['id']: e['text'] for e in menus[code] if e['id']})
        assert all(e['id'] in catalog and isinstance(catalog[e['id']], str)
                   for e in menus['en'] if e['id']), f'Incomplete {code} menu translation'
        files[path] = json.dumps(catalog, ensure_ascii=False, indent=2) + '\n'
    for path, text in files.items():
        if check:
            assert path.read_text(encoding='utf-8') == text, f'Stale generated file: {path}'
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
    print('Original menus: 103 commands, 9 popups, both languages match binary resources; '
          'portable tree and 3 catalogs verified')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    run(parser.parse_args().check)
