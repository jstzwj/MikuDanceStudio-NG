"""Qt Linguist catalog helpers for generated original-MMD controls and menus.

English TS source strings are authoritative. --generate writes the ID/source
declarations consumed by lupdate and the runtime's English fallback.
"""
import argparse
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'translations'
HEADER = DIRECTORY / 'messages.hpp'


def path_for(code):
    return DIRECTORY / f'mikudancestudio_{code}.ts'


def messages(code):
    return ET.parse(path_for(code)).getroot().findall('./context/message')


def load_catalog(code):
    return {m.attrib['id']: m.findtext('translation', '') for m in messages(code)}


def serialize(tree):
    ET.indent(tree, space='    ')
    return '<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE TS>\n' + ET.tostring(
        tree, encoding='unicode', short_empty_elements=False) + '\n'


def updated_catalog(code, values):
    path = path_for(code)
    tree = ET.parse(path).getroot()
    changed = False
    existing = {m.attrib['id'] for m in tree.findall('./context/message')}
    sources = {m.attrib['id']: m.findtext('source', '') for m in messages('en')}
    for identifier, value in values.items():
        if identifier not in existing:
            message = ET.SubElement(tree.find('context'), 'message', id=identifier)
            ET.SubElement(message, 'source').text = value if code == 'en' else sources[identifier]
            ET.SubElement(message, 'translation').text = value
            changed = True
    for message in tree.findall('./context/message'):
        identifier = message.attrib['id']
        if identifier not in values:
            continue
        translation = message.find('translation')
        if (translation.text or '') != values[identifier]:
            translation.text = values[identifier]
            changed = True
        if code == 'en' and message.findtext('source', '') != values[identifier]:
            message.find('source').text = values[identifier]
            changed = True
    return serialize(tree) if changed else path.read_text(encoding='utf-8')


def header():
    rows = ['// Generated by scripts/translation_catalog.py --generate. Do not edit.',
            '#pragma once', '#include <QtGlobal>',
            'namespace mikudancestudio::qt {',
            'struct TranslationMessage { const char* id; const char* source; };',
            'inline constexpr TranslationMessage kTranslationMessages[] = {']
    for message in messages('en'):
        source = json.dumps(message.findtext('source', ''), ensure_ascii=False)
        identifier = json.dumps(message.attrib['id'])
        rows.extend([f'    //% {source}', f'    {{QT_TRID_NOOP({identifier}), {source}}},'])
    rows.extend(['};', 'struct EmptyTranslation { const char* id; const char* language; };',
                 'inline constexpr EmptyTranslation kEmptyTranslations[] = {'])
    for path in sorted(DIRECTORY.glob('mikudancestudio_*.ts')):
        tree = ET.parse(path).getroot()
        for message in tree.findall('./context/message'):
            if message.findtext('source', '') and not message.findtext('translation', ''):
                rows.append('    {' + json.dumps(message.attrib['id']) + ', ' +
                            json.dumps(tree.attrib['language']) + '},')
    return '\n'.join(rows + ['};', '}', ''])


def check():
    reference = {m.attrib['id']: m.findtext('source', '') for m in messages('en')}
    assert len(reference) == len(messages('en')), 'Duplicate English translation ID'
    placeholders = lambda text: sorted(re.findall(r'%(?:L?\d+|n)', text))
    for path in sorted(DIRECTORY.glob('mikudancestudio_*.ts')):
        tree = ET.parse(path).getroot()
        entries = tree.findall('./context/message')
        assert len(entries) == len(reference), path
        assert {m.attrib['id'] for m in entries} == set(reference), path
        for message in entries:
            identifier = message.attrib['id']
            source = message.findtext('source', '')
            translated = message.findtext('translation', '')
            assert source == reference[identifier], (path, identifier, 'stale source')
            assert message.find('translation').get('type') not in ('unfinished', 'vanished'), (
                path, identifier, 'unfinished translation')
            assert placeholders(source) == placeholders(translated), (path, identifier, 'placeholders')
    assert HEADER.read_text(encoding='utf-8') == header(), 'Stale messages.hpp; run --generate'
    print(f'Qt Linguist: {len(reference)} stable IDs; all catalogs and placeholders verified')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    arguments = parser.parse_args()
    if arguments.generate:
        HEADER.write_text(header(), encoding='utf-8', newline='\n')
    else:
        check()
